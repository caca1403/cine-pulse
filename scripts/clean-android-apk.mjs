import { existsSync, unlinkSync, writeFileSync } from 'node:fs';

// Vite copies public/cinepulse.apk into dist for website downloads. Do not
// package that APK inside the Android app during Capacitor sync.
const bundledApk = new URL('../android/app/src/main/assets/public/cinepulse.apk', import.meta.url);
if (existsSync(bundledApk)) unlinkSync(bundledApk);

// Ensure capacitor.settings.gradle uses the dual-resolver so it builds
// both locally (pnpm) and on CI runners (npm).
const settingsGradlePath = new URL('../android/capacitor.settings.gradle', import.meta.url);
const dualResolverContent = `// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN
// Extended with npm/pnpm dual-resolver for CI compatibility

def resolveCapacitorDir = { String npmPath, String pnpmPattern ->
    File standardDir = new File(npmPath)
    if (standardDir.exists()) return standardDir
    File pnpmDir = new File('../node_modules/.pnpm')
    if (pnpmDir.exists()) {
        File[] matches = pnpmDir.listFiles({ dir, name -> name.startsWith(pnpmPattern) } as FilenameFilter)
        if (matches && matches.length > 0) {
            File candidate = new File(matches[0], npmPath.replace('../node_modules/', 'node_modules/'))
            if (candidate.exists()) return candidate
        }
    }
    return standardDir
}

include ':capacitor-android'
project(':capacitor-android').projectDir = resolveCapacitorDir('../node_modules/@capacitor/android/capacitor', '@capacitor+android')

include ':capacitor-app'
project(':capacitor-app').projectDir = resolveCapacitorDir('../node_modules/@capacitor/app/android', '@capacitor+app')

include ':capacitor-status-bar'
project(':capacitor-status-bar').projectDir = resolveCapacitorDir('../node_modules/@capacitor/status-bar/android', '@capacitor+status-bar')
`;

writeFileSync(settingsGradlePath, dualResolverContent, 'utf8');
